import { chromium } from '@playwright/test';
const [q, out, eye, target] = process.argv.slice(2);
const browser = await chromium.launch({ headless: true, args: ['--enable-unsafe-webgpu', '--use-angle=metal'] });
const page = await browser.newPage({ viewport: { width: 960, height: 600 } });
page.on('console', (m) => console.log(`[console.${m.type()}]`, m.text()));
await page.goto(`http://localhost:5199/viewer-test.html?${q}`);
await page.waitForFunction(() => window.__splat && (window.__splat.loaded || window.__splat.error), null, { timeout: 60000 });
await page.waitForTimeout(500);
await page.evaluate(([e, t]) => { const v = window.__splat.viewer; v.lookAt(JSON.parse(e), JSON.parse(t), true); }, [eye, target]);
await page.waitForTimeout(1000);
console.log(JSON.stringify(await page.evaluate(() => window.__splat.stats)));
await page.screenshot({ path: out });
await browser.close();
